export function classify(value: number): string {
  if (value === 1) return 'a';
  if (value === 2) return 'b';
  if (value === 3) return 'c';
  if (value === 4) return 'd';
  if (value === 5) return 'e';
  if (value === 6) return 'f';
  if (value === 7) return 'g';
  if (value === 8) return 'h';
  if (value === 9) return 'i';
  if (value === 10) return 'j';
  return 'z';
}
